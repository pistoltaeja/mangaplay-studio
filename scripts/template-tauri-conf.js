#!/usr/bin/env bun
/**
 * template-tauri-conf.js — Single source of truth for app metadata.
 *
 * Reads app-metadata.json (the ONLY place a human edits app metadata)
 * and writes:
 *   1. src-tauri/tauri.conf.json  — full template render
 *   2. src-tauri/Cargo.toml       — `version = "X.Y.Z"` line patched in place
 *   3. package.json               — `"version": "X.Y.Z"` field patched in place
 *
 * `version` lives in app-metadata.json and propagates to all three files.
 * Anywhere else that has a version is a bug — there should be no other
 * version literal in the repo.
 */

import { readFile, writeFile } from "fs/promises";
import { join } from "path";
import { currentFrontendDirName } from "./lib/frontend-dir.js";

const ROOT = join(import.meta.dirname, "..");
const REPO_ROOT = join(import.meta.dirname, "..", "..");
const META_PATH = join(REPO_ROOT, "mangaplay-studio-configs", "app-metadata.json");
const TEMPLATE_PATH = join(ROOT, "src-tauri", "tauri.conf.json.template");
const TAURI_CONF_PATH = join(ROOT, "src-tauri", "tauri.conf.json");
const CARGO_TOML_PATH = join(ROOT, "src-tauri", "Cargo.toml");
const PACKAGE_JSON_PATH = join(ROOT, "package.json");
const ANDROID_PROPS_PATH = join(ROOT, "src-tauri", "gen", "android", "app", "tauri.properties");

/** Validate that a string looks like a semver MAJOR.MINOR.PATCH. */
function assertSemver(version) {
    if (!/^\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?$/.test(version)) {
        throw new Error(
            `app-metadata.json "version" = "${version}" is not valid semver (MAJOR.MINOR.PATCH).`
        );
    }
}

/** Render `tauri.conf.json` from the template. */
async function renderTauriConf(meta) {
    const templateRaw = await readFile(TEMPLATE_PATH, "utf8");
    let output = templateRaw;

    for (const [key, value] of Object.entries(meta)) {
        if (key.startsWith("$")) continue;
        const placeholder = `{{${key}}}`;
        const strValue = String(value);

        const signingFields = ["appleDeveloperId", "appleTeamId", "windowsCertSubject", "updatePubkey"];
        if (!signingFields.includes(key) && strValue.startsWith("PLACEHOLDER")) {
            throw new Error(`app-metadata.json field "${key}" is still PLACEHOLDER. Fill it in before building.`);
        }

        output = output.replaceAll(placeholder, strValue);
    }

    const tauriRuntimeVars = new Set(["target", "current_version", "arch", "ext"]);
    const unreplaced = (output.match(/\{\{(\w+)\}\}/g) || [])
        .filter(p => !tauriRuntimeVars.has(p.slice(2, -2)));
    if (unreplaced.length > 0) {
        throw new Error(`Unreplaced placeholders in tauri.conf.json.template: ${unreplaced.join(", ")}`);
    }

    await writeFile(TAURI_CONF_PATH, output);
}

/**
 * Patch the top-level `[package].version = "..."` line in src-tauri/Cargo.toml.
 * Only the FIRST occurrence is replaced — that's the crate's package version.
 * Other version lines (dependencies' `version = "..."`) are NOT touched.
 */
async function patchCargoToml(version) {
    const raw = await readFile(CARGO_TOML_PATH, "utf8");
    // Match: a line starting with `version = "X.Y.Z"` AT INDENTATION 0,
    // i.e. inside [package]. Stops at the first [section] header before it.
    const lines = raw.split("\n");
    let inPackage = false;
    let patched = false;
    for (let i = 0; i < lines.length; i++) {
        const line = lines[i];
        const sectionMatch = line.match(/^\[([^\]]+)\]/);
        if (sectionMatch) {
            inPackage = sectionMatch[1] === "package";
            continue;
        }
        if (inPackage && /^version\s*=\s*"[^"]*"\s*$/.test(line)) {
            lines[i] = `version = "${version}"`;
            patched = true;
            break;
        }
    }
    if (!patched) {
        throw new Error(`Could not find [package] version = "..." line in Cargo.toml`);
    }
    await writeFile(CARGO_TOML_PATH, lines.join("\n"));
}

/**
 * Patch the top-level `"version": "..."` field in package.json.
 * Reads + writes JSON to preserve structure exactly.
 */
async function patchPackageJson(version) {
    const raw = await readFile(PACKAGE_JSON_PATH, "utf8");
    const pkg = JSON.parse(raw);
    if (pkg.version === version) return; // no change
    pkg.version = version;
    // Preserve indentation — read original then format with 4-space indent
    // (matches the existing file's style).
    const formatted = JSON.stringify(pkg, null, 4) + "\n";
    await writeFile(PACKAGE_JSON_PATH, formatted);
}

/**
 * Patch `tauri.android.versionCode` + `tauri.android.versionName` in the
 * Android Gradle properties file. Only runs when the file exists (it's
 * generated by `tauri android init` and may not be present on every dev
 * machine — silently skip in that case).
 *
 * versionCode is monotonically derived from MAJOR.MINOR.PATCH:
 *   versionCode = MAJOR * 10000 + MINOR * 100 + PATCH
 * This keeps the integer monotonic while leaving room for two digits in
 * MINOR / PATCH. Future releases keep climbing without manual bumps.
 */
async function patchAndroidProperties(version) {
    let raw;
    try { raw = await readFile(ANDROID_PROPS_PATH, "utf8"); }
    catch (_) { return; } // file not present — skip silently

    const m = version.match(/^(\d+)\.(\d+)\.(\d+)/);
    if (!m) return;
    const versionCode = parseInt(m[1], 10) * 10000 + parseInt(m[2], 10) * 100 + parseInt(m[3], 10);

    const lines = raw.split("\n");
    let codeFound = false;
    let nameFound = false;
    for (let i = 0; i < lines.length; i++) {
        if (/^tauri\.android\.versionCode\s*=/.test(lines[i])) {
            lines[i] = `tauri.android.versionCode=${versionCode}`;
            codeFound = true;
        }
        else if (/^tauri\.android\.versionName\s*=/.test(lines[i])) {
            lines[i] = `tauri.android.versionName=${version}`;
            nameFound = true;
        }
    }
    if (!codeFound) lines.push(`tauri.android.versionCode=${versionCode}`);
    if (!nameFound) lines.push(`tauri.android.versionName=${version}`);
    await writeFile(ANDROID_PROPS_PATH, lines.join("\n"));
}

async function main() {
    const metaRaw = await readFile(META_PATH, "utf8");
    const meta = JSON.parse(metaRaw);

    const common = meta.common ?? {};

    // Resolve the target platform block. MPS_BUILD_PLATFORM is set by build-app.js
    // before this script runs. Fall back to merging both desktop blocks (legacy
    // behaviour) when the env var is absent (e.g. direct invocation without build-app.js).
    const buildPlatform = process.env.MPS_BUILD_PLATFORM;
    let platformBlock;
    if (buildPlatform === "windows") {
        platformBlock = meta.windows ?? {};
    } else if (buildPlatform === "osx") {
        platformBlock = meta.osx ?? {};
    } else {
        // Legacy / unknown: merge both desktop blocks; osx wins on collision.
        platformBlock = { ...(meta.windows ?? {}), ...(meta.osx ?? {}) };
    }

    const resolvedVersion = platformBlock.version;
    if (!resolvedVersion) {
        throw new Error(`app-metadata.json is missing "version" in the "${buildPlatform ?? "windows/osx"}" block.`);
    }
    assertSemver(resolvedVersion);

    // Flatten for template rendering: common first, then ALL desktop platform
    // blocks (the shared tauri.conf.json.template references signing fields
    // from both windows and osx sections regardless of target platform).
    // Platform block applied last so its keys win on collision. version is
    // pinned to resolvedVersion so a future per-platform divergence is correct
    // even when the two platform blocks have different version values.
    const flatMeta = { ...common, ...(meta.windows ?? {}), ...(meta.osx ?? {}), ...platformBlock };
    flatMeta.version = resolvedVersion;

    // Per-UX-mode frontend dir baked into tauri.conf.json's `frontendDist`.
    // Release builds embed the per-variant frontend tree so a mobile build
    // can't ship a standalone bundle (or vice versa). See
    // scripts/lib/frontend-dir.js for the naming convention.
    flatMeta.frontendDist = `../build/mangaplay-studio/${currentFrontendDirName()}`;

    await renderTauriConf(flatMeta);
    await patchCargoToml(resolvedVersion);
    await patchPackageJson(resolvedVersion);
    await patchAndroidProperties(resolvedVersion);

    console.log(`Version ${resolvedVersion} (platform: ${buildPlatform ?? "legacy"}) propagated to tauri.conf.json, Cargo.toml, package.json, tauri.properties (if present)`);
}

main().catch((e) => {
    console.error("template-tauri-conf failed:", e.message);
    process.exit(1);
});
